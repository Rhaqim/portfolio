import type { CollectionEntry } from "astro:content";
import { bulletsById, contact, education, jobs, languages, skills, type Job } from "@data/resume";

export type CompanyEntry = CollectionEntry<"companies">;
export type Theme = CompanyEntry["data"]["theme"];

/** A resume ready to render: the canonical one, or a company's tailored cut. */
export type ResumeModel = {
	contact: typeof contact;
	summary: string;
	jobs: (Omit<Job, "bullets"> & { bullets: { id: string; text: string; group?: string }[] })[];
	skills: { id: string; label: string; items: string[] }[];
	education: typeof education;
	languages: typeof languages;
};

/** Resolve a company's tailored resume against src/data/resume.ts. */
export function tailoredResume(entry: CompanyEntry): ResumeModel {
	const t = entry.data.resume;
	return {
		contact,
		summary: t.summary,
		jobs: t.jobs.flatMap((tj) => {
			const job = jobs.find((j) => j.id === tj.id);
			if (!job) return [];
			return [{
				...job,
				bullets: tj.bullets.flatMap((b) => {
					const src = bulletsById.get(b.ref);
					return src ? [{ id: b.ref, text: b.text ?? src.text, group: src.group }] : [];
				}),
			}];
		}),
		skills: t.skills.flatMap((s) => {
			const group = skills.find((g) => g.id === s.id);
			return group ? [{ ...group, items: s.items.filter((i) => group.items.includes(i)) }] : [];
		}),
		education,
		languages,
	};
}

/** Text of a resume bullet, for evidence quotes on a company page. */
export const bulletText = (id: string) => bulletsById.get(id)?.text;

/** Google Fonts stylesheet URL for a theme's two families. */
export function fontHref(theme: Theme) {
	const fams = [...new Set([theme.heading, theme.body])].map(
		(f) => `family=${f.replaceAll(" ", "+")}:wght@400;500;600;700`,
	);
	return `https://fonts.googleapis.com/css2?${fams.join("&")}&display=swap`;
}

/** CSS custom properties that re-skin the site's tokens for one company. */
export function themeVars(theme: Theme) {
	const font = (f: string) => `"${f}", ui-sans-serif, system-ui, sans-serif`;
	return [
		`--bg: ${theme.bg}`,
		`--bg-raised: ${theme.surface}`,
		`--bg-sunken: ${theme.surface}`,
		`--fg: ${theme.fg}`,
		`--fg-mid: ${theme.muted}`,
		`--fg-dim: ${theme.muted}`,
		`--fg-faint: ${theme.line}`,
		`--line: ${theme.line}`,
		`--line-strong: ${theme.line}`,
		`--red: ${theme.accent}`,
		`--red-bright: ${theme.accent}`,
		`--red-wash: color-mix(in srgb, ${theme.accent} 12%, transparent)`,
		`--on-accent: ${theme.onAccent}`,
		`--cloud: ${theme.accent}`,
		`--radius: ${theme.radius}px`,
		`--font-sans: ${font(theme.body)}`,
		`--font-heading: ${font(theme.heading)}`,
	].join("; ");
}

